import jsPDF from 'jspdf';
import { formatINR } from '../gst';
import { formatEBN, formatToNICDate, GST_STATE_CODES } from '../eway-bill/utils';
import { BRAND_LOGO_BASE64, BRAND_QR_CODE_BASE64 } from '../brand-assets';

export function generateEWayBillPDF(ewb: any): jsPDF {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth(); // 210 mm
  const marginX = 10;
  const contentWidth = 190;
  const rightX = marginX + contentWidth;

  const black = [0, 0, 0] as const;
  const darkGray = [40, 40, 40] as const;
  const midGray = [100, 100, 100] as const;
  const lightGray = [220, 220, 220] as const;
  const tableHeaderBg = [240, 240, 245] as const;
  const sectionBg = [245, 245, 250] as const;

  doc.setLineWidth(0.2);
  doc.setDrawColor(black[0], black[1], black[2]);

  let currentY = 10;

  // ==========================================
  // 1. TOP HEADER (GOVERNMENT e-Way Bill Standard)
  // ==========================================
  // Header Logo & Branding
  try {
    doc.addImage(BRAND_LOGO_BASE64, 'PNG', marginX, currentY, 16, 16);
  } catch (e) {
    // fallback
  }

  // Header Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(black[0], black[1], black[2]);
  doc.text('e-Way Bill', pageWidth / 2, currentY + 4, { align: 'center' });

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.setTextColor(midGray[0], midGray[1], midGray[2]);
  doc.text('Government of India — Form GST EWB-01', pageWidth / 2, currentY + 8.5, { align: 'center' });
  doc.setFontSize(7);
  doc.text('(See rule 138 of the Central Goods and Services Tax Rules, 2017)', pageWidth / 2, currentY + 12, { align: 'center' });

  // Status Badge on top right
  const isCancelled = ewb.status === 'cancelled';
  const isExpired = ewb.status === 'expired';
  const badgeText = isCancelled ? 'CANCELLED' : isExpired ? 'EXPIRED' : 'ACTIVE';
  const badgeBg = isCancelled ? [254, 226, 226] : isExpired ? [254, 243, 199] : [220, 252, 231];
  const badgeColor = isCancelled ? [220, 38, 38] : isExpired ? [217, 119, 6] : [22, 101, 52];

  doc.setFillColor(badgeBg[0], badgeBg[1], badgeBg[2]);
  doc.roundedRect(rightX - 24, currentY, 24, 6, 1, 1, 'F');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7.5);
  doc.setTextColor(badgeColor[0], badgeColor[1], badgeColor[2]);
  doc.text(badgeText, rightX - 12, currentY + 4.2, { align: 'center' });

  currentY += 18;

  // Watermark if Cancelled
  if (isCancelled) {
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(45);
    doc.setTextColor(240, 200, 200);
    doc.text('CANCELLED', pageWidth / 2, 150, { align: 'center', angle: 45 });
  }

  // ==========================================
  // 2. PRIMARY EBN & VALIDITY SUMMARY BOX
  // ==========================================
  const box1Y = currentY;
  const box1H = 34;
  doc.setDrawColor(black[0], black[1], black[2]);
  doc.rect(marginX, box1Y, contentWidth, box1H);

  // Left Details
  const col1X = marginX + 3;
  const col1ValX = marginX + 38;
  const qrX = rightX - 32;

  // Row 1: E-Way Bill No.
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(black[0], black[1], black[2]);
  doc.text('e-Way Bill No:', col1X, box1Y + 6);
  doc.setFontSize(10);
  doc.setTextColor(15, 23, 42); // slate-900
  doc.text(formatEBN(ewb.eway_bill_number), col1ValX, box1Y + 6);

  // Row 2: Generated Date & By
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.5);
  doc.setTextColor(darkGray[0], darkGray[1], darkGray[2]);
  doc.text('Generated Date:', col1X, box1Y + 12);
  doc.setFont('helvetica', 'bold');
  doc.text(ewb.eway_bill_date || formatToNICDate(ewb.created_at), col1ValX, box1Y + 12);

  doc.setFont('helvetica', 'normal');
  doc.text('Generated By:', col1X, box1Y + 18);
  doc.setFont('helvetica', 'bold');
  doc.text(`${ewb.from_gstin} - ${ewb.from_name}`, col1ValX, box1Y + 18);

  // Row 3: Valid From & Until
  doc.setFont('helvetica', 'normal');
  doc.text('Valid From:', col1X, box1Y + 24);
  doc.setFont('helvetica', 'bold');
  doc.text(ewb.eway_bill_date || '—', col1ValX, box1Y + 24);

  doc.setFont('helvetica', 'normal');
  doc.text('Valid Until:', col1X, box1Y + 30);
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(isExpired ? 220 : 0, 0, 0);
  doc.text(`${ewb.valid_until || '—'} (Approx ${ewb.distance_km || 20} km)`, col1ValX, box1Y + 30);

  // QR Code on right side of Box 1
  try {
    doc.addImage(BRAND_QR_CODE_BASE64, 'PNG', qrX, box1Y + 2.5, 29, 29);
  } catch (e) {
    // fallback rectangle
    doc.setDrawColor(lightGray[0], lightGray[1], lightGray[2]);
    doc.rect(qrX, box1Y + 2.5, 29, 29);
    doc.setFontSize(6);
    doc.text('QR VERIFICATION', qrX + 14.5, box1Y + 17, { align: 'center' });
  }

  currentY = box1Y + box1H + 4;

function fmtINR(val?: number): string {
  if (val === undefined || isNaN(val)) return 'Rs. 0';
  return 'Rs. ' + Math.round(val).toLocaleString('en-IN');
}

  // ==========================================
  // 3. PART - A (Details of Goods & Parties)
  // ==========================================
  doc.setFillColor(sectionBg[0], sectionBg[1], sectionBg[2]);
  doc.rect(marginX, currentY, contentWidth, 6, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(black[0], black[1], black[2]);
  doc.text('PART - A (Details of Goods & Parties)', marginX + 3, currentY + 4.2);

  currentY += 6;

  // Part-A Key-Value Table
  const partARows = [
    {
      label1: '1. GSTIN of Supplier',
      val1: `${ewb.from_gstin}\n(${ewb.from_name || 'AL AMEEN WELDING WORKS'})`,
      label2: '2. Place of Dispatch',
      val2: `${ewb.from_place || 'Salem'}, ${GST_STATE_CODES[ewb.from_state_code] || 'TN'} - ${ewb.from_pincode || '636001'}`,
    },
    {
      label1: '3. GSTIN of Recipient',
      val1: `${ewb.to_gstin || 'URP'}\n(${ewb.to_name || 'Customer'})`,
      label2: '4. Place of Delivery',
      val2: `${ewb.to_place || 'Salem'}, ${GST_STATE_CODES[ewb.to_state_code] || 'TN'} - ${ewb.to_pincode || '636001'}`,
    },
    {
      label1: '5. Document No. & Date',
      val1: `Invoice #${ewb.doc_number || ewb.invoice_number || '—'}\ndt. ${formatToNICDate(ewb.doc_date)}`,
      label2: '6. Transaction Type',
      val2: ewb.transaction_type === 'regular' ? 'Regular (Outward Supply)' : String(ewb.transaction_type).toUpperCase(),
    },
    {
      label1: '7. Value of Goods',
      val1: fmtINR(ewb.total_taxable_amount),
      label2: '8. Total Invoice Value',
      val2: fmtINR(ewb.total_invoice_value),
    },
    {
      label1: '9. Main HSN Code',
      val1: ewb.items && ewb.items.length > 0 ? String(ewb.items[0].hsn_code) : '7308',
      label2: '10. Reason for Transportation',
      val2: ewb.sub_supply_type === '1' ? 'Outward - Supply' : 'Outward - Others',
    },
  ];

  const partARowH = 7.0;
  const partAH = partARows.length * partARowH;
  doc.rect(marginX, currentY, contentWidth, partAH);
  doc.line(marginX + contentWidth / 2, currentY, marginX + contentWidth / 2, currentY + partAH); // vertical divider

  partARows.forEach((row, i) => {
    const rowY = currentY + i * partARowH;
    if (i > 0) doc.line(marginX, rowY, rightX, rowY);

    // Left Column
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(midGray[0], midGray[1], midGray[2]);
    doc.text(row.label1, marginX + 3, rowY + 3.2);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(black[0], black[1], black[2]);
    const splitVal1 = doc.splitTextToSize(row.val1, 54);
    doc.text(splitVal1, marginX + 38, rowY + 3.2);

    // Right Column
    const rightColX = marginX + contentWidth / 2 + 3;
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(midGray[0], midGray[1], midGray[2]);
    doc.text(row.label2, rightColX, rowY + 3.2);

    doc.setFont('helvetica', 'bold');
    doc.setTextColor(black[0], black[1], black[2]);
    const splitVal2 = doc.splitTextToSize(row.val2, 54);
    doc.text(splitVal2, rightColX + 38, rowY + 3.2);
  });

  currentY += partAH + 4;

  // ==========================================
  // 4. ITEM LIST & TAX BREAKUP TABLE
  // ==========================================
  const itemCols = [
    { title: 'Item Description', width: 62, align: 'left' },
    { title: 'HSN', width: 18, align: 'center' },
    { title: 'Qty', width: 18, align: 'center' },
    { title: 'Taxable (Rs.)', width: 24, align: 'right' },
    { title: 'CGST (Rs.)', width: 22, align: 'right' },
    { title: 'SGST (Rs.)', width: 22, align: 'right' },
    { title: 'IGST (Rs.)', width: 24, align: 'right' },
  ];

  // Header Row
  doc.setFillColor(tableHeaderBg[0], tableHeaderBg[1], tableHeaderBg[2]);
  doc.rect(marginX, currentY, contentWidth, 6, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  doc.setTextColor(black[0], black[1], black[2]);

  let headerX = marginX;
  itemCols.forEach((col) => {
    const textX = col.align === 'right' ? headerX + col.width - 2 : col.align === 'center' ? headerX + col.width / 2 : headerX + 2;
    doc.text(col.title, textX, currentY + 4.2, { align: col.align as any });
    headerX += col.width;
  });

  currentY += 6;

  // Table Body Rows
  const items = ewb.items && ewb.items.length > 0 ? ewb.items : [
    {
      product_name: 'Rolling Shutter & Accessories',
      hsn_code: '7308',
      quantity: 1,
      unit: 'NOS',
      taxable_amount: ewb.total_taxable_amount,
      cgst_rate: 9,
      cgst_amount: ewb.cgst_amount,
      sgst_rate: 9,
      sgst_amount: ewb.sgst_amount,
      igst_rate: 0,
      igst_amount: ewb.igst_amount,
      total_amount: ewb.total_invoice_value,
    }
  ];

  const itemRowH = 5.2;
  items.slice(0, 6).forEach((it: any) => {
    doc.rect(marginX, currentY, contentWidth, itemRowH);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(6.8);
    doc.setTextColor(darkGray[0], darkGray[1], darkGray[2]);

    let colX = marginX;
    // Desc
    doc.text((it.product_name || 'Component').substring(0, 36), colX + 2, currentY + 3.6);
    colX += itemCols[0].width;
    // HSN
    doc.text(String(it.hsn_code || '7308'), colX + itemCols[1].width / 2, currentY + 3.6, { align: 'center' });
    colX += itemCols[1].width;
    // Qty
    doc.text(`${it.quantity} ${it.unit || 'NOS'}`, colX + itemCols[2].width / 2, currentY + 3.6, { align: 'center' });
    colX += itemCols[2].width;
    // Taxable
    doc.text(fmtINR(it.taxable_amount), colX + itemCols[3].width - 2, currentY + 3.6, { align: 'right' });
    colX += itemCols[3].width;
    // CGST
    doc.text(it.cgst_amount ? `${fmtINR(it.cgst_amount)} (${it.cgst_rate || 9}%)` : '—', colX + itemCols[4].width - 2, currentY + 3.6, { align: 'right' });
    colX += itemCols[4].width;
    // SGST
    doc.text(it.sgst_amount ? `${fmtINR(it.sgst_amount)} (${it.sgst_rate || 9}%)` : '—', colX + itemCols[5].width - 2, currentY + 3.6, { align: 'right' });
    colX += itemCols[5].width;
    // IGST
    doc.text(it.igst_amount ? `${fmtINR(it.igst_amount)} (${it.igst_rate || 18}%)` : '—', colX + itemCols[6].width - 2, currentY + 3.6, { align: 'right' });

    currentY += itemRowH;
  });

  // Totals Row
  doc.setFillColor(tableHeaderBg[0], tableHeaderBg[1], tableHeaderBg[2]);
  doc.rect(marginX, currentY, contentWidth, 5.5, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(7);
  doc.setTextColor(black[0], black[1], black[2]);
  doc.text('Total Values:', marginX + 2, currentY + 3.8);

  let totalColX = marginX + itemCols[0].width + itemCols[1].width + itemCols[2].width;
  doc.text(fmtINR(ewb.total_taxable_amount), totalColX + itemCols[3].width - 2, currentY + 3.8, { align: 'right' });
  totalColX += itemCols[3].width;
  doc.text(fmtINR(ewb.cgst_amount), totalColX + itemCols[4].width - 2, currentY + 3.8, { align: 'right' });
  totalColX += itemCols[4].width;
  doc.text(fmtINR(ewb.sgst_amount), totalColX + itemCols[5].width - 2, currentY + 3.8, { align: 'right' });
  totalColX += itemCols[5].width;
  doc.text(fmtINR(ewb.igst_amount), totalColX + itemCols[6].width - 2, currentY + 3.8, { align: 'right' });

  currentY += 9;

  // ==========================================
  // 5. PART - B (Vehicle & Transporter Details)
  // ==========================================
  doc.setFillColor(sectionBg[0], sectionBg[1], sectionBg[2]);
  doc.rect(marginX, currentY, contentWidth, 6, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(8.5);
  doc.setTextColor(black[0], black[1], black[2]);
  doc.text('PART - B (Vehicle / Transport Details)', marginX + 3, currentY + 4.2);

  currentY += 6;

  const partBCols = [
    { title: 'Mode', width: 22, align: 'center' },
    { title: 'Vehicle / Trans Doc No.', width: 44, align: 'left' },
    { title: 'From Place', width: 34, align: 'left' },
    { title: 'Entered Date & Time', width: 38, align: 'center' },
    { title: 'Entered By', width: 32, align: 'center' },
    { title: 'Multi-Veh', width: 20, align: 'center' },
  ];

  doc.setFillColor(tableHeaderBg[0], tableHeaderBg[1], tableHeaderBg[2]);
  doc.rect(marginX, currentY, contentWidth, 5.5, 'FD');
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(6.8);
  doc.setTextColor(black[0], black[1], black[2]);

  let bHeaderX = marginX;
  partBCols.forEach((col) => {
    const textX = col.align === 'center' ? bHeaderX + col.width / 2 : bHeaderX + 2;
    doc.text(col.title, textX, currentY + 3.8, { align: col.align as any });
    bHeaderX += col.width;
  });

  currentY += 5.5;

  // Part-B Content Row
  const modeText = ewb.transport_mode === '2' ? 'Rail' : ewb.transport_mode === '3' ? 'Air' : ewb.transport_mode === '4' ? 'Ship' : 'Road';
  const vehNumber = ewb.vehicle_number || (ewb.transporter_doc_no ? `LR: ${ewb.transporter_doc_no}` : '—');
  const enteredDateTime = ewb.eway_bill_date || formatToNICDate(ewb.created_at);

  doc.rect(marginX, currentY, contentWidth, 7);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(7.2);
  doc.setTextColor(darkGray[0], darkGray[1], darkGray[2]);

  let bColX = marginX;
  doc.text(modeText, bColX + partBCols[0].width / 2, currentY + 4.5, { align: 'center' });
  bColX += partBCols[0].width;

  doc.setFont('helvetica', 'bold');
  doc.text(vehNumber, bColX + 2, currentY + 4.5);
  doc.setFont('helvetica', 'normal');
  bColX += partBCols[1].width;

  doc.text(ewb.from_place || 'Salem', bColX + 2, currentY + 4.5);
  bColX += partBCols[2].width;

  doc.text(enteredDateTime, bColX + partBCols[3].width / 2, currentY + 4.5, { align: 'center' });
  bColX += partBCols[3].width;

  doc.text(ewb.from_gstin ? ewb.from_gstin.substring(0, 15) : '33CRHPD7107H1Z3', bColX + partBCols[4].width / 2, currentY + 4.5, { align: 'center' });
  bColX += partBCols[4].width;

  doc.text('No', bColX + partBCols[5].width / 2, currentY + 4.5, { align: 'center' });

  currentY += 11;

  // Transporter Details Note
  if (ewb.transporter_name || ewb.transporter_id) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(midGray[0], midGray[1], midGray[2]);
    doc.text(
      `Transporter: ${ewb.transporter_name || '—'} | Transporter ID / GSTIN: ${ewb.transporter_id || '—'} | Doc No: ${ewb.transporter_doc_no || '—'}`,
      marginX + 2,
      currentY
    );
    currentY += 5;
  }

  // ==========================================
  // 6. BOTTOM LEGAL DISCLAIMER & SIGNATURE
  // ==========================================
  const footerY = 270;
  doc.setDrawColor(lightGray[0], lightGray[1], lightGray[2]);
  doc.line(marginX, footerY, rightX, footerY);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(6.5);
  doc.setTextColor(midGray[0], midGray[1], midGray[2]);
  doc.text(
    'Note: This is a computer generated document issued under the Goods and Services Tax Rules, 2017. QR code verification available.',
    marginX,
    footerY + 4
  );
  doc.text(
    `Al Ameen Automation | 13-A, Omalur Main Road, Salem - 636001 | Phone: +91 94432 44321 / +91 98427 12345 | Web: https://al-ameen-automation.in`,
    marginX,
    footerY + 8
  );

  return doc;
}
